// Получить УМК для конкретного класса и предмета.
// Возвращает объект { authors, title, publisher } или null, если УМК не найден.
export function getUmk(grade, subject) {
  const g = Number(grade);
  if (!g || g < 1 || g > 11) return null;
  const gradeUmk = UMK_BY_GRADE[g];
  if (!gradeUmk) return null;
  return gradeUmk[subject] || null;
}

// Все доступные предметы для класса.
export function subjectsForGrade(grade) {
  const g = Number(grade);
  const gradeUmk = UMK_BY_GRADE[g];
  if (!gradeUmk) return [];
  return Object.keys(gradeUmk);
}

// Все поддерживаемые классы.
export const UMK_GRADES = Object.keys(UMK_BY_GRADE).map(Number).sort((a, b) => a - b);
